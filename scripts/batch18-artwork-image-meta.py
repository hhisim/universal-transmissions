#!/usr/bin/env python3
"""batch18-artwork-image-meta.py — regenerate src/data/artwork-image-meta.ts.

Reads the intrinsic dimensions of each artwork master so a page can reserve the correct
aspect box instead of cropping the work into a fixed square. It only READS the masters;
public/artworks is never modified by this or any Batch 18 step.

Run from the repository root:  python3 scripts/batch18-artwork-image-meta.py
"""
import os
import re

from PIL import Image

SRC = "src/data/artworks.ts"
OUT = "src/data/artwork-image-meta.ts"

slugs = re.findall(r'slug:\s*"([^"]+)"', open(SRC).read())
rows = []
for slug in slugs:
    path = f"public/artworks/{slug}/main.jpg"
    if os.path.isfile(path):
        rows.append((slug, *Image.open(path).size))

body = [
    "/**",
    " * artwork-image-meta.ts - intrinsic dimensions of each artwork master.",
    " *",
    " * Generated by reading the master files under public/artworks/<slug>/main.jpg. The masters",
    " * themselves are untouched; this only records what they already are, so a page can",
    " * reserve the correct aspect box instead of cropping the work into a fixed square.",
    " * Regenerate with scripts/batch18-artwork-image-meta.py if a master is replaced.",
    " */",
    "",
    "export interface ArtworkImageMeta { width: number; height: number }",
    "",
    "export const ARTWORK_IMAGE_META: Record<string, ArtworkImageMeta> = {",
]
body += [f'  "{s}": {{ width: {w}, height: {h} }},' for s, w, h in rows]
body += [
    "};",
    "",
    "/** Aspect ratio (width / height) for a master, or null when unknown. */",
    "export function artworkAspect(slug: string): number | null {",
    "  const m = ARTWORK_IMAGE_META[slug];",
    "  return m ? m.width / m.height : null;",
    "}",
    "",
]
open(OUT, "w").write("\n".join(body))
print(f"wrote {OUT} with {len(rows)} entries")
